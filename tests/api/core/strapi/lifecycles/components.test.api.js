'use strict';

const path = require('path');
const fs = require('fs-extra');

const { createTestBuilder } = require('api-tests/builder');
const { createStrapiInstance } = require('api-tests/strapi');
const { createContentAPIRequest } = require('api-tests/request');

const COMPONENT_UID = 'default.hooked-compo';
const CONTENT_TYPE_UID = 'api::product-with-hooked-compo.product-with-hooked-compo';

const component = {
  displayName: 'hooked-compo',
  attributes: {
    name: { type: 'string' },
  },
};

const contentType = {
  displayName: 'product-with-hooked-compo',
  singularName: 'product-with-hooked-compo',
  pluralName: 'product-with-hooked-compos',
  attributes: {
    compo: {
      type: 'component',
      component: COMPONENT_UID,
    },
    compos: {
      type: 'component',
      component: COMPONENT_UID,
      repeatable: true,
    },
  },
};

/**
 * `src/components/default/hooked-compo.lifecycles.js`, written next to the schema
 * generated by the test builder. It is a regular user-land lifecycles file; the only
 * test-specific parts are the absolute `@strapi/utils` path (so the thrown error is
 * the same class the running instance checks against) and the global call log.
 */
const lifecyclesFile = `'use strict';

const { errors } = require(${JSON.stringify(require.resolve('@strapi/utils'))});

const log = (action, event) => {
  global.__componentLifecycleCalls.push({
    action,
    uid: event.model.uid,
    data: event.params.data ? { ...event.params.data } : undefined,
  });
};

module.exports = {
  beforeCreate(event) {
    const { data } = event.params;

    if (data.name === 'forbidden') {
      throw new errors.ValidationError('The name "forbidden" is not allowed');
    }

    data.name = String(data.name).toUpperCase();
    log('beforeCreate', event);
  },
  beforeUpdate(event) {
    log('beforeUpdate', event);
  },
  afterDelete(event) {
    log('afterDelete', event);
  },
};
`;

let builder;
let strapi;
let rq;
let lifecyclesPath;

const callsFor = (action) =>
  global.__componentLifecycleCalls.filter((call) => call.action === action);

describe('Lifecycles - components', () => {
  beforeAll(async () => {
    builder = createTestBuilder();
    await builder.addComponent(component).addContentType(contentType).build();

    const appDir = path.dirname(process.env.ENV_PATH);
    lifecyclesPath = path.join(
      appDir,
      'src',
      'components',
      'default',
      'hooked-compo.lifecycles.js'
    );
    await fs.outputFile(lifecyclesPath, lifecyclesFile);
    global.__componentLifecycleCalls = [];

    strapi = await createStrapiInstance();
    rq = await createContentAPIRequest({ strapi });
    rq.setURLPrefix(`/api/${contentType.pluralName}`);
  });

  afterAll(async () => {
    await strapi.destroy();
    await fs.remove(lifecyclesPath);
    delete global.__componentLifecycleCalls;
    await builder.cleanup();
  });

  beforeEach(() => {
    global.__componentLifecycleCalls = [];
  });

  test('The lifecycles file is attached to the component model', () => {
    expect(strapi.getModel(COMPONENT_UID).lifecycles).toMatchObject({
      beforeCreate: expect.any(Function),
      beforeUpdate: expect.any(Function),
      afterDelete: expect.any(Function),
    });
    expect(strapi.db.metadata.get(COMPONENT_UID).lifecycles.beforeCreate).toBeInstanceOf(Function);
  });

  test('beforeCreate runs when the component is created through its parent entry', async () => {
    const res = await rq.post('/', {
      body: { data: { compo: { name: 'alpha' } } },
      qs: { populate: ['compo'] },
    });

    expect(res.statusCode).toBe(201);
    expect(res.body.data.compo.name).toBe('ALPHA');
    expect(callsFor('beforeCreate')).toEqual([
      {
        action: 'beforeCreate',
        uid: COMPONENT_UID,
        data: expect.objectContaining({ name: 'ALPHA' }),
      },
    ]);
  });

  test('A repeatable component runs the hook once per item', async () => {
    const res = await rq.post('/', {
      body: { data: { compos: [{ name: 'one' }, { name: 'two' }] } },
      qs: { populate: ['compos'] },
    });

    expect(res.statusCode).toBe(201);
    expect(res.body.data.compos.map((item) => item.name)).toEqual(['ONE', 'TWO']);
    expect(callsFor('beforeCreate')).toHaveLength(2);
  });

  test('beforeUpdate runs when the parent entry updates the component', async () => {
    const created = await rq.post('/', {
      body: { data: { compo: { name: 'before' } } },
      qs: { populate: ['compo'] },
    });
    global.__componentLifecycleCalls = [];

    const res = await rq.put(`/${created.body.data.documentId}`, {
      body: { data: { compo: { id: created.body.data.compo.id, name: 'after' } } },
      qs: { populate: ['compo'] },
    });

    expect(res.statusCode).toBe(200);
    expect(res.body.data.compo.name).toBe('after');
    expect(callsFor('beforeUpdate')).toEqual([
      {
        action: 'beforeUpdate',
        uid: COMPONENT_UID,
        data: expect.objectContaining({ name: 'after' }),
      },
    ]);
  });

  test('afterDelete runs when the parent entry is deleted', async () => {
    const created = await rq.post('/', {
      body: { data: { compo: { name: 'doomed' } } },
    });
    global.__componentLifecycleCalls = [];

    const res = await rq.delete(`/${created.body.data.documentId}`);

    expect(res.statusCode).toBe(204);
    expect(callsFor('afterDelete')).toEqual([
      { action: 'afterDelete', uid: COMPONENT_UID, data: undefined },
    ]);
  });

  test('A ValidationError thrown from a component hook rejects the request and rolls back the whole entry', async () => {
    const entriesBefore = await strapi.db.query(CONTENT_TYPE_UID).count();

    const res = await rq.post('/', {
      body: { data: { compos: [{ name: 'rolled-back' }, { name: 'forbidden' }] } },
    });

    expect(res.statusCode).toBe(400);
    expect(res.body.error).toMatchObject({
      status: 400,
      name: 'ValidationError',
      message: 'The name "forbidden" is not allowed',
    });

    // the first component row was inserted before the second one threw: it must be gone
    expect(await strapi.db.query(COMPONENT_UID).count({ where: { name: 'ROLLED-BACK' } })).toBe(0);
    expect(await strapi.db.query(CONTENT_TYPE_UID).count()).toBe(entriesBefore);
  });
});
