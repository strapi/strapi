const getSuperAdminWithUsersCount = () => findOneWithUsersCount({ code: SUPER_ADMIN_CODE });

/** Create superAdmin, Author and Editor role is no role already exist
 */
const createRolesIfNoneExist = async () => {
  const someRolesExist = await exists();
  if (someRolesExist) {
    return;
  }

  const { actionProvider } = getService('permission');

  const allActions = actionProvider.values();
  const contentTypesActions = allActions.filter((a) => a.section === 'contentTypes');

  // create 3 roles
  const superAdminRole = await create({
    name: 'Super Admin',
    code: 'strapi-super-admin',
    description: 'Super Admins can access and manage all features and settings.',
  });

  await getService('user').assignARoleToAll(superAdminRole.id);

  const editorRole = await create({
    name: 'Editor',
    code: 'strapi-editor',
    description: 'Editors can manage and publish contents including those of other users.',
  });

  const authorRole = await create({
    name: 'Author',
    code: 'strapi-author',
    description: 'Authors can manage the content they have created.',
  });

  // create content-type permissions for each role
  // Exclude non-displayed content types (e.g. plugin::users-permissions.role) from Editor/Author
  // since those types are in explorer.read subjects only for super admin relation reads.
  const nonDisplayedUids = Object.values(strapi.contentTypes as Record<string, any>)
    .filter((ct) => ct?.pluginOptions?.['content-manager']?.visible === false)
    .map((ct) => ct.uid as string);

  const editorPermissions = getService('content-type').getPermissionsWithNestedFields(
    contentTypesActions,
    {
      restrictedSubjects: ['plugin::users-permissions.user', ...nonDisplayedUids],
    }
  ) as Permission[];

  const authorPermissions = editorPermissions
    .filter(({ action }: any) => action !== ACTIONS.publish)
    .map((permission: any) =>
      permissionDomain.create({ ...permission, conditions: ['admin::is-creator'] })
    );

  editorPermissions.push(...getDefaultPluginPermissions());
  authorPermissions.push(...getDefaultPluginPermissions({ isAuthor: true }));

  // assign permissions to roles
  await addPermissions(editorRole.id, editorPermissions);
  await addPermissions(authorRole.id, authorPermissions);
};

const getDefaultPluginPermissions = ({ isAuthor = false } = {}) => {
  const conditions = isAuthor ? ['admin::is-creator'] : [];

  // add plugin permissions for each role
  return [
    { action: 'plugin::upload.read', conditions },
    { action: 'plugin::upload.configure-view' },
    { action: 'plugin::upload.assets.create' },
    { action: 'plugin::upload.assets.update', conditions },
    { action: 'plugin::upload.assets.download' },
    { action: 'plugin::upload.assets.copy-link' },
  ].map(permissionDomain.create);
};

/** Display a warning if the role superAdmin doesn't exist
 *  or if the role is not assigned to at least one user
 */
const displayWarningIfNoSuperAdmin = async () => {
  const superAdminRole = await getSuperAdminWithUsersCount();
  const someUsersExists = await getService('user').exists();

  if (!superAdminRole) {
    strapi.log.warn("Your application doesn't have a super admin role.");
  } else if (someUsersExists && superAdminRole.usersCount === 0) {
    strapi.log.warn("Your application doesn't have a super admin user.");
  }
};

/**
 * Assign permissions to a role
 * @param roleId - role Data.ID
 * @param {Array<Permission{action,subject,fields,conditions}>} permissions - permissions to assign to the role
 */
const assignPermissions = async (
  roleId: Data.ID,
  permissions: Array<Pick<Permission, 'action' | 'subject' | 'conditions'>> = []
) => {
  await validatePermissionsExist(permissions);

  // Internal actions are not handled by the role service, so any permission
  // with an internal action is filtered out
  const internalActions = new Set(
    getService('permission')
      .actionProvider.values()
      .filter((action) => action.section === 'internal')
      .map((action) => action.actionId)
  );

  const superAdmin = await getService('role').getSuperAdmin();
  const isSuperAdmin = superAdmin && superAdmin.id === roleId;
  const assignRole = <T extends object>(permission: T) => ({ ...permission, role: roleId });

  const permissionsWithRole = permissions
    // Add the role attribute to every permission
    .map(assignRole)
    // Transform each permission into a Permission instance
    .map(permissionDomain.create);

  const existingPermissions = await getService('permission').findMany({
    where: { role: { id: roleId } },
    populate: ['role'],
  });

  const permissionsToAdd = differenceWith(
    permissionsWithRole,
    existingPermissions,
    arePermissionsEqual
  ).filter((permission: Permission) => !internalActions.has(permission.action));

  const permissionsToDelete = differenceWith(
    existingPermissions,
    permissionsWithRole,
    arePermissionsEqual
  ).filter((permission: Permission) => !internalActions.has(permission.action));

  const permissionsToReturn = differenceBy(permissionsToDelete, existingPermissions, 'id');

  if (permissionsToDelete.length > 0) {
    await getService('permission').deleteByIds(
      permissionsToDelete.map((permission) => permission?.id)
    );
  }

  if (permissionsToAdd.length > 0) {
    const newPermissions = await addPermissions(roleId, permissionsToAdd);
    permissionsToReturn.push(...newPermissions);
  }

  if (!isSuperAdmin && (permissionsToAdd.length || permissionsToDelete.length)) {
    await getService('metrics').sendDidUpdateRolePermissions();
  }

  if (permissionsToAdd.length > 0 || permissionsToDelete.length > 0) {
    await getService('api-token-admin').syncPermissionsForRole(roleId);
  }

  return permissionsToReturn;
};

/**
 * Make sure a requester cannot grant a role permissions they do not hold themselves. A request
 * made with an admin token is limited by the token's permissions and, unless the token owner is
 * a super admin, by the owner's.
 * Permissions the role already carries, or narrower versions of one of them, are not checked:
 * they grant nothing new, and removing them is always allowed. A narrower version is covered,
 * atom by atom (field × locale × condition), by one of the role's own rows read the way the
 * engine enforces them, so fewer fields, locales or conditions are accepted, but recombining two
 * rows or dropping the last condition (unconditional) is checked against the requester.
 * A localized row stored with no or empty `locales` grants no locale, but the role editor and
 * i18n's `willValidateUpdatePermissions` hook give it the default locale. Resending or narrowing
 * that row is accepted. It is stored as sent when the requester holds it, and otherwise keeps its
 * stored `locales`, so the save grants nothing the requester does not hold.
 * A permission with action parameters is a separate ability for the engine
 * (`<action>?<parameters>`): it is only covered by held permissions with the same action, subject
 * and action parameters.
 * @param requester - the admin user or admin token performing the update
 * @param roleId - the role being updated
 * @param permissions - the permissions requested for the role, after `willValidateUpdatePermissions`
 * @returns the permissions to store
 */
const checkPermissionsCeiling = async (
  requester: CeilingRequester,
  roleId: Data.ID,
  permissions: CreatePermissionPayload[] = []
): Promise<CreatePermissionPayload[]> => {
  const ceilings = await findRequesterCeilings(requester);

  // Super admins hold every permission
  if (ceilings.length === 0) {
    return permissions;
  }

  const permissionService = getService('permission');
  const sanitizeConditions = permissionDomain.sanitizeConditions(
    // @ts-expect-error - same Condition type mismatch as in `addPermissions`
    permissionService.conditionProvider
  );

  const existingPermissions = await permissionService.findMany({
    where: { role: { id: roleId } },
  });

  const isOnRole = (permission: Permission) =>
    existingPermissions.some((existing) => arePermissionsEqual(permission, existing));

  const existingEnforced = await toEnforcedCeilingPermissions(existingPermissions);

  // Parameterized permissions are registered as `<action>?<parameters>`, which the atom rule
  // does not describe, so they are never treated as a narrowing
  const narrowsRolePermission = (stored: Permission) =>
    isEmpty(stored.actionParameters) &&
    permissionDomain.ceiling.isPermissionWithinCeiling(stored, existingEnforced);

  // The role's rows that grant no locale (no or empty `locales`) and that the hook gives one, with
  // that hooked reading. The hook gets copies, and each row is paired with the hooked row of the
  // same id that differs from it in `locales` only, whatever the handlers return.
  const hookedPermissions = (await hooks.willValidateUpdatePermissions.call(
    cloneDeep(existingPermissions)
  )) as unknown;

  const grantsNoLocale = (permission: Permission) => {
    const locales = permission.properties?.locales;

    return locales === undefined || (Array.isArray(locales) && locales.length === 0);
  };

  const findHookedReading = (row: Permission) => {
    const hooked =
      row.id !== undefined && Array.isArray(hookedPermissions)
        ? (hookedPermissions as Permission[]).find((permission) => permission?.id === row.id)
        : undefined;

    const isLocalesOnlyChange =
      hooked !== undefined &&
      hooked.action === row.action &&
      (hooked.subject ?? null) === (row.subject ?? null) &&
      isEqual(hooked.conditions ?? [], row.conditions ?? []) &&
      isEqual(hooked.actionParameters ?? {}, row.actionParameters ?? {}) &&
      isEqual(omit(hooked.properties ?? {}, 'locales'), omit(row.properties ?? {}, 'locales')) &&
      !isEqual(hooked.properties?.locales, row.properties?.locales);

    return isLocalesOnlyChange ? hooked : undefined;
  };

  const unlocalizedRows = await Promise.all(
    existingPermissions
      .filter(grantsNoLocale)
      .map((row) => ({ row, hooked: findHookedReading(row) }))
      .filter((pair): pair is { row: Permission; hooked: Permission } => pair.hooked !== undefined)
      .map(async ({ row, hooked }) => ({
        row,
        hooked,
        hookedEnforced: await toEnforcedCeilingPermissions([hooked]),
      }))
  );

  // The row a permission resends or narrows once the row is given the default locale
  const findUnlocalizedRow = (permission: Permission, stored: Permission) =>
    unlocalizedRows.find(
      ({ hooked, hookedEnforced }) =>
        hooked.action === stored.action &&
        (hooked.subject ?? null) === (stored.subject ?? null) &&
        (arePermissionsEqual(permission, hooked) ||
          arePermissionsEqual(stored, hooked) ||
          (isEmpty(stored.actionParameters) &&
            permissionDomain.ceiling.isPermissionWithinCeiling(stored, hookedEnforced)))
    )?.row;

  const withRowLocales = (
    permission: CreatePermissionPayload,
    row: Permission
  ): CreatePermissionPayload => {
    const properties = omit(permission.properties ?? {}, 'locales');

    return {
      ...permission,
      properties:
        row.properties && 'locales' in row.properties
          ? { ...properties, locales: row.properties.locales }
          : properties,
    };
  };

  // The requested locales are checked as sent: i18n's `willValidateUpdatePermissions` hook has
  // already turned a missing or empty `locales` on a localized subject into the default locale.
  // The requested conditions are checked as they will be stored, without the unregistered ones.
  // A permission equal to a row of the role, as sent or as stored, leaves that row unchanged, and
  // one covered by the role's own rows only narrows them. One that only matches an unlocalized
  // row is stored as sent when the requester holds it, and with the row's own `locales` otherwise.
  const requested = permissions.map((payload) => {
    const permission = permissionDomain.create(payload);
    const stored = sanitizeConditions(permission) as Permission;
    const isKept = isOnRole(permission) || isOnRole(stored) || narrowsRolePermission(stored);

    return {
      payload,
      permission,
      stored,
      isKept,
      unlocalizedRow: isKept ? undefined : findUnlocalizedRow(permission, stored),
    };
  });

  const newPermissions = requested.filter(({ isKept }) => !isKept);

  // The held permissions with action parameters, only loaded when a new permission has some
  const parameterizedCeilings = newPermissions.some(
    ({ stored }) => !isEmpty(stored.actionParameters)
  )
    ? await findRequesterParameterizedCeilings(requester)
    : [];

  const isWithinCeilings = (stored: Permission) =>
    isEmpty(stored.actionParameters)
      ? ceilings.every((held) => permissionDomain.ceiling.isPermissionWithinCeiling(stored, held))
      : parameterizedCeilings.every((held) =>
          permissionDomain.ceiling.isParameterizedPermissionWithinCeiling(stored, held)
        );

  const toStore = requested.map(({ payload, stored, isKept, unlocalizedRow }) =>
    !isKept && unlocalizedRow && !isWithinCeilings(stored)
      ? withRowLocales(payload, unlocalizedRow)
      : payload
  );

  const rejectedPermissions = newPermissions
    .filter(({ stored, unlocalizedRow }) => !unlocalizedRow && !isWithinCeilings(stored))
    .map(({ permission }) => permission);

  if (rejectedPermissions.length > 0) {
    throw new ForbiddenError('You cannot grant permissions you do not hold yourself', {
      permissions: rejectedPermissions.map((permission) =>
        pick(permission, ['action', 'subject', 'properties', 'conditions'])
      ),
    });
  }

  return toStore;
};

/**
 * A permission to add to a role, with the action parameters to store as is.
 */
type AddPermissionPayload<TActionParameters extends object> = Omit<
  CreatePermissionPayload,
  'actionParameters'
> & {
  actionParameters?: TActionParameters;
};

/**
 * A permission that {@link addPermissions} stored: the database gives it a number id, and it keeps
 * the action parameters it was given (`{}` when none were given).
 */
export type AddedPermission<TActionParameters extends object = object> = Omit<
  Permission,
  'id' | 'actionParameters' | 'subject'
> & {
  id: number;
  actionParameters: TActionParameters;
  subject: string | null;
};

const addPermissions = async <TActionParameters extends object = object>(
  roleId: Data.ID,
  permissions: AddPermissionPayload<TActionParameters>[]
): Promise<AddedPermission<TActionParameters>[]> => {
  const { conditionProvider, createMany } = getService('permission');
  const { sanitizeConditions } = permissionDomain;

  const permissionsWithRole = permissions
    .map((permission) => ({ ...permission, role: roleId }))
    // @ts-expect-error - refactor domain/permission Condition type, as it's now expecting
    // a string but it should be a Condition interface
    .map(sanitizeConditions(conditionProvider))
    .map(permissionDomain.create);

  // `createMany` declares the wider `Permission`: `id` as `Data.ID`, `actionParameters` as `object`
  return createMany(permissionsWithRole) as Promise<AddedPermission<TActionParameters>[]>;
};

const isContentTypeAction = (action: Action) => action.section === CONTENT_TYPE_SECTION;

/**
 * Reset super admin permissions (giving it all permissions)
 */
const resetSuperAdminPermissions = async () => {
  const superAdminRole = await getService('role').getSuperAdmin();
  if (!superAdminRole) {
    return;
  }

  const permissionService = getService('permission');
  const contentTypeService = getService('content-type');

  const allActions = permissionService.actionProvider.values() as Action[];

  const contentTypesActions = allActions.filter((action) => isContentTypeAction(action));
  const otherActions = allActions.filter((action) => !isContentTypeAction(action));

  // First, get the content-types permissions
  const permissions = contentTypeService.getPermissionsWithNestedFields(
    contentTypesActions
  ) as Permission[];

  // Then add every other permission
  const otherPermissions = otherActions.reduce((acc, action) => {
    const { actionId, subjects } = action;

    if (Array.isArray(subjects)) {
      acc.push(
        ...subjects.map((subject) => permissionDomain.create({ action: actionId, subject }))
      );
    } else {
      acc.push(permissionDomain.create({ action: actionId }));
    }

    return acc;
  }, [] as Permission[]);

  permissions.push(...otherPermissions);

  const transformedPermissions = (await hooks.willResetSuperAdminPermissions.call(
    permissions
  )) as Permission[];

  await assignPermissions(superAdminRole.id, transformedPermissions);
};

/**
 * Check if a user object includes the super admin role
 */
const hasSuperAdminRole = (user: AdminUser): boolean => {
  const roles = _.get(user, 'roles', []) as AdminRole[];

  return roles.map((role) => role?.code).includes(SUPER_ADMIN_CODE);
};

