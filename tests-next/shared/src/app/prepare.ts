import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

import { testPluginConfigEntry } from '../test-plugin';
import { buildAdmin, hasAdminBuild } from './build';
import { REPO_ROOT, inheritedEnv } from './config';
import { appPaths, generateApp, type App } from './generate';

/**
 * Stored in the app folder. Its name must not match `*.env*`: the VS Code Playwright extension
 * restarts its test server when such a file changes, which drops the run in progress.
 */
const MARKER_FILE = '.tests-app.json';

/** `TESTS_REGENERATE=true` deletes and regenerates the app, then builds its admin panel. */
const REGENERATE_ENV_VAR = 'TESTS_REGENERATE';

interface Marker {
  app: string;
  admin: string;
}

export interface PrepareAppOptions {
  name: string;
  /** Build the admin panel too. Default: true. */
  admin?: boolean;
}

export interface PreparedApp {
  app: App;
  /** The app was (re)generated by this call. */
  generated: boolean;
  /** The admin panel was (re)built by this call. */
  built: boolean;
}

const sha = () => createHash('sha256');

/** Every file under `dir`, in a stable order, as absolute paths. */
const filesUnder = (dir: string): string[] =>
  fs
    .readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => path.join(entry.parentPath, entry.name))
    .sort();

/**
 * What shapes the generated app: the Strapi version (its package.json), the generation code of
 * this package and what create-strapi-app copies from (its `dist` and `templates`). Hashed by
 * content, so a `yarn build` that changes nothing keeps the app.
 */
const appFingerprint = () => {
  const hash = sha();
  hash.update(fs.readFileSync(require.resolve('@strapi/strapi/package.json')));
  hash.update(testPluginConfigEntry());
  const createStrapiApp = path.dirname(require.resolve('create-strapi-app/package.json'));
  const sources = [
    path.join(__dirname, 'generate.ts'),
    path.join(__dirname, 'generate-app.cjs'),
    path.join(__dirname, 'config.ts'),
    ...filesUnder(path.join(createStrapiApp, 'dist')),
    ...filesUnder(path.join(createStrapiApp, 'templates')),
  ];
  for (const file of sources) {
    hash.update(file);
    hash.update(fs.readFileSync(file));
  }
  return hash.digest('hex');
};

/**
 * What shapes the admin bundle, on top of the app: the `STRAPI_*` env of the run (the build bakes
 * `STRAPI_ADMIN_*`, `STRAPI_AI_URL` and `STRAPI_ANALYTICS_URL` into the bundle) and the built
 * workspace packages. A `yarn build` or `yarn watch` rewrites their `dist`, so the admin is rebuilt
 * after it: the files' count and newest mtime are enough, and much faster than hashing them.
 */
const adminFingerprint = () => {
  const hash = sha();
  const env = inheritedEnv();
  for (const key of Object.keys(env).sort()) {
    if (key.startsWith('STRAPI_')) {
      hash.update(`${key}=${env[key]}\n`);
    }
  }
  const packagesDir = path.join(REPO_ROOT, 'packages');
  let count = 0;
  let newest = 0;
  for (const group of fs.readdirSync(packagesDir)) {
    const groupDir = path.join(packagesDir, group);
    if (!fs.statSync(groupDir).isDirectory()) {
      continue;
    }
    for (const pkg of fs.readdirSync(groupDir)) {
      const dist = path.join(groupDir, pkg, 'dist');
      if (!fs.existsSync(dist)) {
        continue;
      }
      for (const file of filesUnder(dist)) {
        count += 1;
        newest = Math.max(newest, fs.statSync(file).mtimeMs);
      }
    }
  }
  hash.update(`${count}:${newest}`);
  return hash.digest('hex');
};

const readMarker = (app: App): Marker | undefined => {
  try {
    return JSON.parse(fs.readFileSync(path.join(app.dir, MARKER_FILE), 'utf8'));
  } catch {
    return undefined;
  }
};

/**
 * Generate an app and build its admin panel, or reuse the ones a previous run left when nothing
 * that shapes them changed. For suites that use the same app for every run (ui): regenerating
 * rewrites its `.env`, which makes the VS Code Playwright extension drop the run, and costs about
 * 10 s. An app that scaffolders or seeders change is not reusable: use generateApp() for it.
 *
 * The app is regenerated when the Strapi version, the generation code or create-strapi-app
 * changed, or with TESTS_REGENERATE=true. The admin panel is rebuilt with the app, when the
 * build is missing, or when the `STRAPI_*` env or a workspace package build changed.
 */
export const prepareApp = async ({
  name,
  admin = true,
}: PrepareAppOptions): Promise<PreparedApp> => {
  let app = appPaths(name);
  const marker = readMarker(app);
  const appHash = appFingerprint();

  const generated = process.env[REGENERATE_ENV_VAR] === 'true' || !marker || marker.app !== appHash;
  if (generated) {
    app = await generateApp({ name });
  }

  const adminHash = admin ? adminFingerprint() : '';
  const built = admin && (generated || !hasAdminBuild(app) || marker?.admin !== adminHash);
  if (built) {
    await buildAdmin(app);
  }

  // Written last, so a run interrupted before this point regenerates next time. Left untouched
  // when nothing changed: a reused app keeps every file as it was.
  if (generated || built) {
    const next: Marker = { app: appHash, admin: adminHash };
    fs.writeFileSync(path.join(app.dir, MARKER_FILE), `${JSON.stringify(next, null, 2)}\n`);
  }

  return { app, generated, built };
};
